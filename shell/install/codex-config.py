#!/usr/bin/env python3
"""Initialize Codex defaults or explicitly apply the optional status line."""

import argparse
import copy
import datetime
import json
import re
import sys
import tomllib
from pathlib import Path

HEADER = "# Generated by goldband Codex config installer"


class ConfigError(Exception):
    """A configuration failure safe to report without printing its contents."""


def read_config(path, reason, optional=False):
    if optional and not path.exists() and not path.is_symlink():
        return "", {}
    try:
        text = path.read_bytes().decode("utf-8")
        return text, tomllib.loads(text)
    except (OSError, UnicodeError, tomllib.TOMLDecodeError) as error:
        raise ConfigError(reason) from error


def merge_settings(defaults, preferred):
    result = copy.deepcopy(defaults)
    for key, value in preferred.items():
        if isinstance(value, dict) and isinstance(result.get(key), dict):
            result[key] = merge_settings(result[key], value)
        else:
            result[key] = copy.deepcopy(value)
    return result


def quote(value):
    # JSON basic-string escapes are TOML-compatible except raw DEL.
    return json.dumps(value, ensure_ascii=False).replace("\x7f", "\\u007f")


def key_text(value):
    return value if re.fullmatch(r"[A-Za-z0-9_-]+", value) else quote(value)


def value_text(value):
    if isinstance(value, str):
        return quote(value)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (datetime.datetime, datetime.date, datetime.time)):
        return value.isoformat()
    if isinstance(value, list):
        return "[" + ", ".join(value_text(item) for item in value) + "]"
    if isinstance(value, dict):
        fields = (f"{key_text(key)} = {value_text(item)}" for key, item in value.items())
        return "{ " + ", ".join(fields) + " }"
    raise ConfigError("unsupported-value")


def table_lines(table, prefix=()):
    lines = []
    if prefix:
        lines.append("[" + ".".join(key_text(key) for key in prefix) + "]")
    for key, value in table.items():
        if not isinstance(value, dict):
            lines.append(f"{key_text(key)} = {value_text(value)}")
    for key, value in table.items():
        if isinstance(value, dict):
            lines.append("")
            lines.extend(table_lines(value, (*prefix, key)))
    return lines


def initial_defaults(args):
    _, base = read_config(args.base, "source-unsupported")
    _, local = read_config(args.local, "source-unsupported", optional=True)
    return merge_settings(base, local)


def render(args):
    exists = args.installed.exists() or args.installed.is_symlink()
    original, installed = read_config(args.installed, "invalid-toml", optional=True)
    if args.statusline:
        _, preset = read_config(args.statusline, "source-unsupported")
        if set(preset) != {"tui"} or set(preset["tui"]) != {"status_line"}:
            raise ConfigError("invalid-statusline-preset")
        if "tui" in installed and not isinstance(installed["tui"], dict):
            raise ConfigError("incompatible-table")
        merged = merge_settings(installed, preset)
        if merged == installed:
            return original
        lines = []
    elif exists:
        return original
    else:
        merged = initial_defaults(args)
        lines = [HEADER, "# Initial defaults only; subsequent installs preserve this file."]
    lines.extend(table_lines(merged))
    text = "\n".join(lines) + "\n"
    # Validate the complete output before the shell can replace any user file.
    try:
        tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        raise ConfigError("invalid-output") from error
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("render", "security-advice", "syntax"))
    parser.add_argument("installed", type=Path)
    parser.add_argument("base", nargs="?", type=Path)
    parser.add_argument("local", nargs="?", type=Path)
    parser.add_argument("--statusline", type=Path)
    args = parser.parse_args()
    if args.action != "syntax" and (args.base is None or args.local is None):
        parser.error("render/security-advice require both base and local-default paths")
    try:
        if args.action == "syntax":
            read_config(args.installed, "invalid-toml")
        elif args.action == "render":
            sys.stdout.buffer.write(render(args).encode("utf-8"))
        else:
            _, installed = read_config(args.installed, "invalid-toml")
            _, base = read_config(args.base, "source-unsupported")
            if installed.get("shell_environment_policy") != base.get("shell_environment_policy"):
                print("shell_environment_policy differs from the recommended defaults; review codex/config.toml manually")
    except ConfigError as error:
        print(str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
