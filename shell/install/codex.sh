# This file must be sourced by bash, not executed directly.

is_generated_codex_config() {
    local path="$1"
    [ -f "$path" ] || return 1
    local header
    header="$(head -n 1 "$path" 2>/dev/null)"
    [ "${header%$'\r'}" = '# Generated by goldband Codex config installer' ]
}

emit_codex_profile_without_runtime_state() {
    local path="$1"
    [ -f "$path" ] || return 1
    awk '
        /^\[hooks\.state(\.|\])/ { in_runtime_state = 1; next }
        /^\[tui\.model_availability_nux\]/ { in_runtime_state = 1; next }
        in_runtime_state && /^\[/ { in_runtime_state = 0 }
        !in_runtime_state { print }
    ' "$path"
}

normalize_codex_managed_config() {
    awk '
        /^[[:space:]]*$/ { pending_blanks = pending_blanks "\n"; next }
        {
            if (pending_blanks != "") {
                printf "%s", pending_blanks
                pending_blanks = ""
            }
            print
        }
    '
}

resolve_codex_config_python() {
    CODEX_CONFIG_PYTHON=()
    if command -v python3 >/dev/null 2>&1 && python3 -c 'import tomllib' >/dev/null 2>&1; then
        CODEX_CONFIG_PYTHON=(python3)
    elif command -v python >/dev/null 2>&1 && python -c 'import tomllib' >/dev/null 2>&1; then
        CODEX_CONFIG_PYTHON=(python)
    elif command -v py >/dev/null 2>&1 && py -3 -c 'import tomllib' >/dev/null 2>&1; then
        CODEX_CONFIG_PYTHON=(py -3)
    else
        CODEX_CONFIG_FRESHNESS_REASON="syntax-unverifiable"
        return 1
    fi
}

codex_toml_syntax_valid() {
    resolve_codex_config_python || return 1
    if ! "${CODEX_CONFIG_PYTHON[@]}" "$REPO_DIR/shell/install/codex-config.py" syntax "$1"; then
        CODEX_CONFIG_FRESHNESS_REASON="invalid-toml"
        return 1
    fi
}

is_valid_codex_config() {
    local path="$1"
    CODEX_CONFIG_FRESHNESS_REASON=""
    codex_toml_syntax_valid "$path"
}

codex_profile_installed_from() {
    local src="$1"
    local dest="$2"

    repo_link_points_to "$dest" "$src" && return 0
    [ -f "$src" ] && [ -f "$dest" ] || return 1
    cmp -s \
        <(normalize_codex_managed_config < "$src") \
        <(emit_codex_profile_without_runtime_state "$dest" | normalize_codex_managed_config)
}

install_generated_codex_config() {
    local dest="$CODEX_CONFIG_FILE"
    local preset="${1:-}"
    if ! resolve_codex_config_python; then
        echo "[錯誤] Codex config validation requires Python 3.11+ tomllib." >&2
        return 1
    fi
    mkdir -p "$(dirname "$dest")" || return 1
    local tmp
    tmp="$(mktemp "${dest}.tmp.XXXXXX")" || return 1
    local args=(render "$dest" "$REPO_DIR/codex/config.toml" "$REPO_DIR/codex/local/config.toml")
    [ -z "$preset" ] || args+=(--statusline "$preset")
    if ! "${CODEX_CONFIG_PYTHON[@]}" "$REPO_DIR/shell/install/codex-config.py" "${args[@]}" > "$tmp"; then
        rm -f "$tmp"
        echo "[錯誤] Codex config operation failed; existing configuration was not changed." >&2
        return 1
    fi
    if [ ! -L "$dest" ] && cmp -s "$dest" "$tmp"; then
        rm -f "$tmp"
        echo "  [保留] Codex config.toml — existing settings are current"
        return 0
    fi
    replace_host_config "$dest" "$tmp" || return 1
    echo "  [設定] Codex config.toml — initialized defaults or applied explicit status line"
}

install_codex_statusline() {
    if [ "${1:-explicit}" = "refresh" ]; then
        echo "  [保留] Codex status line — rerun codex-statusline to apply the Goldband preset"
        return 0
    fi
    install_generated_codex_config "$REPO_DIR/codex/statusline.toml"
}

install_codex_profile_configs() {
    local profile_dir="$REPO_DIR/codex/profiles"

    if [ ! -d "$profile_dir" ]; then
        echo -e "  ${YELLOW}[跳過] Codex profile configs — 來源不存在${NC}"
        return
    fi

    local profile_file
    for profile_file in "$profile_dir"/*.config.toml; do
        [ -f "$profile_file" ] || continue
        install_codex_profile_config_file "$profile_file" "$CODEX_DIR/$(basename "$profile_file")" || return 1
    done
}

install_codex_profile_config_file() {
    local src="$1"
    local dest="$2"
    local label="Codex profile $(basename "$src")"

    if [ ! -e "$src" ]; then
        echo -e "  ${YELLOW}[跳過] $label — 來源不存在${NC}"
        return
    fi

    if [ -L "$dest" ]; then
        rm "$dest"
    elif [ -e "$dest" ] && ! cmp -s "$src" "$dest" 2>/dev/null; then
        backup_existing_path "$dest"
    fi

    materialize_file_copy "$src" "$dest" || return 1
    chmod 0644 "$dest" || return 1
    echo -e "  ${GREEN}[安裝] $label (materialized copy)${NC}"
}

install_codex_requirements_file() {
    local src="$REPO_DIR/codex/requirements.toml"
    local dest="$CODEX_REQUIREMENTS_FILE"

    if [ ! -f "$src" ]; then
        echo -e "  ${YELLOW}[跳過] Codex requirements.toml — 來源不存在${NC}"
        return
    fi

    local dest_dir
    dest_dir="$(dirname "$dest")"
    local backup_suffix
    backup_suffix="$(date +%s)"

    local can_write_without_sudo=false
    if [ "$(id -u)" -eq 0 ]; then
        can_write_without_sudo=true
    elif mkdir -p "$dest_dir" 2>/dev/null && [ -w "$dest_dir" ]; then
        can_write_without_sudo=true
    fi

    if $can_write_without_sudo; then
        mkdir -p "$dest_dir"
        if [ -e "$dest" ] && ! cmp -s "$src" "$dest"; then
            cp "$dest" "${dest}.bak.${backup_suffix}"
            echo -e "  ${YELLOW}[備份] Codex requirements.toml -> ${dest}.bak.${backup_suffix}${NC}"
        fi
        cp "$src" "$dest"
        chmod 0644 "$dest"
    elif is_windows_host; then
        echo -e "  ${RED}[錯誤] Codex requirements 需要可寫入的 Windows managed path:${NC} $dest" >&2
        echo -e "  ${CYAN}  請用系統管理員權限建立此目錄並複製 codex/requirements.toml，或用 CODEX_REQUIREMENTS_FILE 指到可寫入的測試路徑。${NC}" >&2
        return 1
    else
        sudo mkdir -p "$dest_dir"
        if sudo test -e "$dest" && ! sudo cmp -s "$src" "$dest"; then
            sudo cp "$dest" "${dest}.bak.${backup_suffix}"
            echo -e "  ${YELLOW}[備份] Codex requirements.toml -> ${dest}.bak.${backup_suffix}${NC}"
        fi
        sudo cp "$src" "$dest"
        sudo chmod 0644 "$dest"
    fi

    echo -e "  ${GREEN}[安裝] Codex managed requirements -> $dest${NC}"
}

is_repo_codex_rule_link() {
    local link_path="$1"
    local base_rules="$REPO_DIR/codex/rules"
    local local_rules="$REPO_DIR/codex/local/rules"

    [ -L "$link_path" ] || return 1

    local target
    target=$(readlink "$link_path")
    case "$target" in
        "$base_rules"/*|"$local_rules"/*)
            return 0
            ;;
        *)
            return 1
            ;;
    esac
}

link_codex_rule_file() {
    local src="$1"
    local dest="$2"
    local label="$3"

    if repo_path_installed_from "$src" "$dest"; then
        if [ -L "$dest" ]; then
            echo -e "  ${GREEN}[已安裝] $label${NC}"
        else
            echo -e "  ${GREEN}[已安裝 (copy fallback)] $label${NC}"
        fi
        return
    fi

    if [ -L "$dest" ]; then
        if is_repo_codex_rule_link "$dest"; then
            rm "$dest"
        else
            backup_existing_path "$dest"
        fi
    elif [ -e "$dest" ]; then
        if [ "$src" = "$REPO_DIR/codex/rules/default.rules" ] && [ "$dest" = "$CODEX_RULES_DIR/goldband.rules" ]; then
            # This reserved name is Goldband's portable baseline, including copy installs.
            # Personal approvals belong to default.rules and are never replaced here.
            backup_existing_path "$dest" || return 1
        else
            echo -e "  ${YELLOW}[保留] $label — 目標已有非 goldband 檔案: $dest${NC}"
            return
        fi
    fi

    create_repo_link "$src" "$dest" || return 1
    if [ "$CREATE_REPO_LINK_MODE" = "copy" ]; then
        echo -e "  ${YELLOW}[安裝 (copy fallback)] $label — 此環境無法建立檔案 symlink${NC}"
    else
        echo -e "  ${GREEN}[安裝 (repo-linked)] $label${NC}"
    fi
}

ensure_codex_local_default_rules() {
    local local_default="$REPO_DIR/codex/local/rules/default.rules"

    if [ -f "$local_default" ]; then
        return
    fi

    mkdir -p "$(dirname "$local_default")"
    {
        echo "# Machine-local Codex execpolicy rules."
        echo "# This ignored file is the writable default target for one-off approvals."
        echo ""
    } > "$local_default"
}

prune_stale_codex_rule_links() {
    local entry
    for entry in "$CODEX_RULES_DIR"/*.rules; do
        if [ ! -e "$entry" ] && [ ! -L "$entry" ]; then
            continue
        fi
        if is_repo_codex_rule_link "$entry"; then
            local target
            target=$(readlink "$entry")
            if [ ! -e "$target" ]; then
                rm "$entry"
            fi
        fi
    done
}

install_codex_rules_dir() {
    local base_rules="$REPO_DIR/codex/rules"
    local local_rules="$REPO_DIR/codex/local/rules"

    if [ ! -d "$base_rules" ]; then
        echo -e "  ${YELLOW}[跳過] Codex Rules — 來源不存在${NC}"
        return
    fi

    if [ -L "$CODEX_RULES_DIR" ]; then
        rm "$CODEX_RULES_DIR"
    elif [ -e "$CODEX_RULES_DIR" ] && [ ! -d "$CODEX_RULES_DIR" ]; then
        backup_existing_path "$CODEX_RULES_DIR"
    fi

    mkdir -p "$CODEX_RULES_DIR" || return 1
    ensure_codex_local_default_rules || return 1
    prune_stale_codex_rule_links || return 1

    local rule_file
    for rule_file in "$base_rules"/*.rules; do
        [ -f "$rule_file" ] || continue
        local dest_name
        dest_name="$(basename "$rule_file")"
        if [ "$dest_name" = "default.rules" ]; then
            dest_name="goldband.rules"
        fi
        link_codex_rule_file "$rule_file" "$CODEX_RULES_DIR/$dest_name" "Codex rule $dest_name" || return 1
    done

    if [ -d "$local_rules" ]; then
        for rule_file in "$local_rules"/*.rules; do
            [ -f "$rule_file" ] || continue
            link_codex_rule_file "$rule_file" "$CODEX_RULES_DIR/$(basename "$rule_file")" "Codex local rule $(basename "$rule_file")" || return 1
        done
    fi
}

codex_portable_rules_have_local_state() {
    local base_rules="$REPO_DIR/codex/rules"
    [ -d "$base_rules" ] || return 1
    grep -R -q -F '/Users/' "$base_rules" ||
        grep -R -q -F '/private/tmp' "$base_rules" ||
        grep -R -q -F '.studio_os_write_token' "$base_rules" ||
        grep -R -q -F 'LaunchAgents' "$base_rules"
}

warn_codex_portable_rules_local_state() {
    if ! codex_portable_rules_have_local_state; then
        return 0
    fi

    echo -e "  ${YELLOW}[警告] Codex portable rules 含有本機 approvals，會阻止 self-update${NC}"
    echo -e "  ${CYAN}  建議執行:${NC} ./install.sh repair-codex-rules"
    echo -e "  ${CYAN}  這會把本機 approvals 從 codex/rules/default.rules 移到 ignored overlay:${NC}"
    echo -e "  ${CYAN}  codex/local/rules/default.rules${NC}"
}

repair_codex_local_rules() {
    local migrator="$REPO_DIR/scripts/migrate-codex-local-rules.py"
    local base_rules="$REPO_DIR/codex/rules/default.rules"
    local local_rules="$REPO_DIR/codex/local/rules/default.rules"

    if [ ! -f "$migrator" ]; then
        echo -e "  ${RED}[錯誤] 找不到 repair script: $migrator${NC}"
        return 1
    fi
    if ! command -v python3 >/dev/null 2>&1; then
        echo -e "  ${RED}[錯誤] repair-codex-rules 需要 python3${NC}"
        return 1
    fi

    python3 "$migrator" --base-rules "$base_rules" --local-rules "$local_rules"
    bash "$REPO_DIR/scripts/check-codex-portability.sh"
    install_codex_rules_dir
}

show_codex_config_status() {
    if [ -e "$CODEX_CONFIG_FILE" ] || [ -L "$CODEX_CONFIG_FILE" ]; then
        if ! is_valid_codex_config "$CODEX_CONFIG_FILE"; then
            case "$CODEX_CONFIG_FRESHNESS_REASON" in
                invalid-toml)
                    echo -e "  ${RED}[invalid]${NC} codex-config — installed config.toml is not valid TOML"
                    echo "    修正 TOML syntax 後再重跑 ./install.sh status。"
                    ;;
                syntax-unverifiable)
                    echo -e "  ${RED}[unverifiable]${NC} codex-config — TOML parser unavailable"
                    echo "    需要 Python 3.11+ tomllib（python3、python 或 py -3）。"
                    ;;
            esac
            GOLDBAND_STATUS_EXIT_CODE=2
        else
            echo -e "  ${GREEN}[OK]${NC} codex-config (valid user settings; defaults are not enforced)"
            show_codex_security_defaults_advice
        fi
    else
        echo -e "  ${RED}[未安裝]${NC} codex-config"
    fi
}

show_codex_security_defaults_advice() {
    local advice
    if ! advice="$("${CODEX_CONFIG_PYTHON[@]}" "$REPO_DIR/shell/install/codex-config.py" \
        security-advice "$CODEX_CONFIG_FILE" "$REPO_DIR/codex/config.toml" \
        "$REPO_DIR/codex/local/config.toml")"; then
        echo "  [unverifiable] Codex security defaults could not be compared"
        GOLDBAND_STATUS_EXIT_CODE=2
    elif [ -n "$advice" ]; then
        echo "  [建議檢查] $advice"
    fi
}
